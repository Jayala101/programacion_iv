void main() {
  print("Operadores Aritméticos");
  
  int numero1 = 8;
  int numero2 = 5;
  
  print("$numero1 + $numero2 = ${numero1 + numero2}");
  print("$numero1 - $numero2 = ${numero1 - numero2}");
  print("$numero1 * $numero2 = ${numero1 * numero2}");
  print("$numero1 / $numero2 = ${numero1 / numero2}");
}